# Pack thresholded rows MSB first, padding the final byte of each row.
# 将阈值化后的各行按高位优先打包，并补齐每行最后一个字节。
def pack(image):
    out = bytearray()
    for y in range(image.height):
        for x in range(0, image.width, 8):
            value = 0
            for bit in range(8):
                if x + bit < image.width and image.getpixel((x + bit, y)) >= 128:
                    value |= 0x80 >> bit
            out.append(value)
    return bytes(out)


# Encode row differences as literal bytes and zero runs, retaining compact raw masks.
# 将相邻行的差分编码为字节段与零游程，并为较小的原始图案保留原始格式。
def encode_mask(raw, width):
    stride = (width + 7) // 8
    assert width <= 128 and len(raw) < 0x8000
    delta = bytes(value ^ (raw[index - stride] if index >= stride else 0)
                  for index, value in enumerate(raw))
    encoded = bytearray()
    at = 0
    while at < len(delta):
        start = at
        if delta[at] == 0:
            while at < len(delta) and delta[at] == 0 and at - start < 128:
                at += 1
            encoded.append(0x80 | (at - start - 1))
        else:
            while at < len(delta) and delta[at] != 0 and at - start < 128:
                at += 1
            encoded.append(at - start - 1)
            encoded.extend(delta[start:at])
    if len(encoded) < len(raw):
        return bytes(encoded), len(encoded)
    return raw, len(raw) | 0x8000


def array(name, data):
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def glyph_image(font, char):
    box = font.getbbox(char, anchor="ls")
    image = Image.new("L", (max(1, box[2] - box[0]), max(1, box[3] - box[1])))
    ImageDraw.Draw(image).text((-box[0], -box[1]), char, font=font, fill=255, anchor="ls")
    return image, box[0], box[1], round(font.getlength(char))


# Complete subset punctuation using Montserrat's dash and comma masks.
# 使用 Montserrat 的连字符和逗号字形补齐子集中的标点。
def text_glyph(font, cp, size):
    if cp in (0x2013, 0x2014):
        image, x, y, _ = glyph_image(font, "-")
        advance = round(size * (0.5 if cp == 0x2013 else 1.0))
        image = image.resize((max(1, advance - 2), image.height))
        return image, 1, y, advance
    if cp in (0x2019, 0x201C, 0x201D):
        image, _, _, advance = glyph_image(font, ",")
        if cp == 0x201C:
            image = image.transpose(Image.Transpose.ROTATE_180)
        count = 1 if cp == 0x2019 else 2
        step = max(image.width + 1, advance)
        combined = Image.new("L", (step * count, image.height))
        for i in range(count):
            combined.paste(image, (i * step, 0))
        return combined, 0, -round(size * 0.73), step * count
    return glyph_image(font, chr(cp))


def fonts():
    notice = """// Montserrat bitmap masks: SIL Open Font License 1.1.
// Copyright 2011 The Montserrat Project Authors (https://github.com/JulietaUla/Montserrat)
// License: card_assets_licenses/Montserrat-OFL.txt.
// Curly quotes and en/em dashes are assembled from this subset's comma and dash.
"""
    h = HEADER + notice + """
#pragma once
#include <stdint.h>

typedef struct {
    uint32_t codepoint, offset;
    uint16_t advance;
    int16_t x_offset, y_offset;
    uint16_t width, height, encoded_bytes;
} card_glyph_t;

typedef struct {
    uint16_t size, ascent, line_height, count;
    const card_glyph_t *glyphs;
    const uint8_t *bitmap;
} card_font_t;

#ifdef __cplusplus
extern "C" {
#endif
const card_font_t *card_font_find(int size);
const card_glyph_t *card_font_glyph(const card_font_t *font, uint32_t codepoint);
#ifdef __cplusplus
}
#endif
"""
    source = HEADER + notice + '#include "card_fonts.h"\n#include <stddef.h>\n#ifdef ESP_PLATFORM\n#include "sdkconfig.h"\n#endif\n\n'
    total = 0
    care_total = 0
    entries = []
    for size in SIZES:
        font = ImageFont.truetype(str(TEXT_FONT), size, layout_engine=ImageFont.Layout.BASIC)
        bitmap = bytearray()
        glyphs = []
        for cp in CHARACTERS:
            image, x, y, advance = text_glyph(font, cp, size)
            box = image.point(lambda v: 255 if v >= 128 else 0).getbbox()
            if box:
                image = image.crop(box)
                x += box[0]
                y += box[1]
                w, height = image.size
                mask = pack(image)
            else:
                w = height = 0
                mask = b""
            encoded, count = encode_mask(mask, w)
            glyphs.append(f"    {{{cp}, {len(bitmap)}, {advance}, {x}, {y}, {w}, {height}, {count}}},")
            bitmap.extend(encoded)
        ascent, descent = font.getmetrics()
        guard = "#if !CONFIG_HOMEHUB_CARE_BOARD\n" if size == 96 else ""
        source += guard + array(f"bitmap_{size}", bitmap)
        source += f"static const card_glyph_t glyphs_{size}[] = {{\n" + "\n".join(glyphs) + "\n};\n\n"
        if guard: source += "#endif\n"
        entry = f"    {{{size}, {ascent}, {ascent + descent}, {len(glyphs)}, glyphs_{size}, bitmap_{size}}},"
        entries.append(guard + entry + ("\n#endif" if guard else ""))
        size_bytes = len(bitmap) + len(glyphs) * 20 + 16
        total += size_bytes
        if size != 96: care_total += size_bytes
    source += "static const card_font_t fonts[] = {\n" + "\n".join(entries) + "\n};\n"
    source += """
const card_font_t *card_font_find(int size) {
    for (unsigned i = 0; i < sizeof(fonts) / sizeof(fonts[0]); i++) {
        if (fonts[i].size == size) return &fonts[i];
    }
    return NULL;
}

const card_glyph_t *card_font_glyph(const card_font_t *font, uint32_t codepoint) {
    unsigned lo = 0, hi = font->count;
    while (lo < hi) {
        unsigned mid = lo + (hi - lo) / 2;
        if (font->glyphs[mid].codepoint < codepoint) lo = mid + 1;
        else hi = mid;
    }
    return lo < font->count && font->glyphs[lo].codepoint == codepoint
        ? &font->glyphs[lo] : &font->glyphs['?' - 0x20];
}
"""
    (OUT / "card_fonts.h").write_text(h)
    (OUT / "card_fonts.c").write_text(source)
    return total, care_total


def icons():
    notice = """// Material Symbols Rounded bitmap masks: Apache License 2.0.
// Copyright 2026 Google LLC.  All Rights Reserved.
// License: card_assets_licenses/MaterialSymbols-LICENSE.txt.
// FILL=1, GRAD=0, opsz=48, wght=500. Source: .cache/fonts/MaterialSymbolsRounded.ttf.
"""
    h = HEADER + notice + """
#pragma once
#include <stdint.h>

typedef struct {
    const char *name;
    const uint8_t *bitmap;
    uint16_t size, width, height;
    int16_t x_offset, y_offset;
    uint16_t encoded_bytes;
} card_icon_t;

#ifdef __cplusplus
extern "C" {
#endif
const card_icon_t *card_icon_find(const char *name, int size);
#ifdef __cplusplus
}
#endif
"""
    source = HEADER + notice + '#include "card_icons.h"\n#include <stddef.h>\n#include <string.h>\n\n'
    codepoints = dict(line.split() for line in ICON_FONT.with_suffix(".codepoints").read_text().splitlines())
    entries = []
    total = 0
    for name in ICONS:
        source += f'static const char name_{name}[] = "{name}";\n'
        total += len(name) + 1
        for size in ICON_SIZES:
            font = ImageFont.truetype(str(ICON_FONT), size, layout_engine=ImageFont.Layout.BASIC)
            values = {b"Fill": 1, b"Grade": 0, b"Optical Size": 48, b"Weight": 500}
            font.set_variation_by_axes([values[axis["name"]] for axis in font.get_variation_axes()])
            char = chr(int(codepoints[name], 16))
            bounds = font.getbbox(char)
            image = Image.new("L", (size, size))
            ImageDraw.Draw(image).text(((size - bounds[2] + bounds[0]) // 2 - bounds[0],
                                        (size - bounds[3] + bounds[1]) // 2 - bounds[1]),
                                       char, font=font, fill=255)
            box = image.point(lambda v: 255 if v >= 128 else 0).getbbox()
            if not box:
                raise ValueError(f"Empty icon: {name} {size}")
            cropped = image.crop(box)
            data, count = encode_mask(pack(cropped), cropped.width)
            symbol = f"icon_{name}_{size}"
            source += array(symbol, data)
            entries.append(f"    {{name_{name}, {symbol}, {size}, {cropped.width}, {cropped.height}, {box[0]}, {box[1]}, {count}}},")
            total += len(data) + 20
    source += "static const card_icon_t icons[] = {\n" + "\n".join(entries) + "\n};\n"
    source += """
const card_icon_t *card_icon_find(const char *name, int size) {
    if (!name) return NULL;
    for (unsigned i = 0; i < sizeof(icons) / sizeof(icons[0]); i++) {
        if (icons[i].size == size && !strcmp(icons[i].name, name)) return &icons[i];
    }
    return NULL;
}
"""
    (OUT / "card_icons.h").write_text(h)
    (OUT / "card_icons.c").write_text(source)
    return total


def main():
    (font_bytes, care_font_bytes), icon_bytes = fonts(), icons()
    total = font_bytes + icon_bytes
    print(f"Fonts: {font_bytes} bytes; icons: {icon_bytes} bytes; total: {total} / {160 * 1024} bytes")
    print(f"Care Board fonts: {care_font_bytes} bytes; icons: {icon_bytes} bytes; total: {care_font_bytes + icon_bytes} bytes")
    if total > 160 * 1024:
        raise SystemExit("Card assets exceed 160 KiB")
    manifest = {"fonts_bytes": font_bytes, "icons_bytes": icon_bytes,
                "care_fonts_bytes": care_font_bytes, "care_total_bytes": care_font_bytes + icon_bytes,
                "total_bytes": total, "font_sizes": SIZES, "icon_sizes": ICON_SIZES,
                "encoding": "row-xor-zero-rle",
                "sources": {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                            for p in (TEXT_FONT, ICON_FONT, ICON_FONT.with_suffix(".codepoints"))}}
    (OUT / "card_assets_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
